#!/usr/bin/env python3
"""Opt-in real-image/location acceptance. Requires an already running provider.

This starts only its own headless probe and never starts/restarts the provider
or requests host privacy access. The caller must supply a real screenshot:
  python3 extras/devices/tests/verify-standalone.py --image /absolute/screenshot.png
A static screenshot validates the image path, not live desktop capture.
"""
import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import shutil
import time
import uuid

from PIL import Image, ImageStat
from acceptance_support import CLI, REPO, ProbeRun, save_json


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", required=True, type=Path, help="Absolute path to a real screenshot; never generated by this test")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--profile")
    parser.add_argument("--dylib", type=Path, default=REPO / "build/devices/SimRunDevices.dylib")
    args = parser.parse_args()
    if not args.image.is_absolute() or not args.image.is_file():
        parser.error("--image must be an existing absolute path")
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    profile = args.profile or "standalone-image-" + stamp + "-" + uuid.uuid4().hex[:6]
    out = (args.output or REPO / ("build/devices/acceptance/standalone-acceptance-" + stamp)).resolve()
    out.mkdir(parents=True, exist_ok=True)
    reference = Image.open(args.image).convert("RGB")
    width, height = reference.size
    if width < 2 or height < 2 or width > 8192 or height > 8192 or width % 2 or height % 2:
        parser.error("Screenshot dimensions must be positive even values from 2 to 8192; this test never resizes the input")
    evidence_image = out / ("input-screenshot" + args.image.suffix.lower())
    if evidence_image != args.image.resolve():
        shutil.copy2(args.image, evidence_image)
    checks = []
    first_rgb = reference.getpixel((0, 0))
    report = dict(profile=profile, image=str(args.image), inputEvidence=evidence_image.name,
                  imageSHA256=hashlib.sha256(args.image.read_bytes()).hexdigest(),
                  inputSize=[width, height], inputFirstRGB=first_rgb, dylib=str(args.dylib.resolve()),
                  scope="real screenshot image source and location; not live desktop capture", checks=checks)

    def save():
        report["passed"] = report.get("completed", False) and bool(checks) and all(check["passed"] for check in checks) and "failure" not in report
        save_json(out / "acceptance.json", report)

    def check(name, condition, evidence):
        checks.append(dict(name=name, passed=bool(condition), evidence=evidence))
        save()
        if not condition:
            raise AssertionError(name)
        print("PASS", name, flush=True)

    def location(**changes):
        config = dict(latitude=31.22046, longitude=121.45801, horizontalAccuracy=5,
                      authorization="notDetermined", requestAuthorization="authorizedWhenInUse")
        config.update(changes)
        save_json(out / "location.json", config)

    camera = dict(name="Real screenshot acceptance", authorization="authorized", requestAuthorization="authorized",
                  devices=[dict(id="simrun-" + position, name="Screenshot " + position, position=position,
                                source=dict(kind="image", path=str(evidence_image))) for position in ("back", "front")])
    save_json(out / "camera.json", camera)
    location()
    run = ProbeRun(REPO / "build/devices/DeviceProbe.app", "dev.simrun.DeviceProbe", profile, out, args.dylib)

    def state(name):
        value = run.state()
        save_json(out / (name + ".json"), value)
        return value

    def wait_state(name, condition, timeout=15):
        deadline = time.monotonic() + timeout
        last = None
        while time.monotonic() < deadline:
            last = run.state()
            if condition(last):
                save_json(out / (name + ".json"), last)
                return last
            time.sleep(.15)
        save_json(out / (name + ".json"), last)
        raise TimeoutError(name + ": expected state did not arrive")

    def configure_permission(status):
        path = out / ("camera-" + status + ".json")
        save_json(path, dict(authorization=status, requestAuthorization="authorized"))
        result = json.loads(run.evaluate('return objc.send("SRSimRunCamera","configureFile:",' + json.dumps(str(path)) + ');'))
        check("camera permission configuration " + status, result is True, path.name)

    def compare_photo(path, name):
        captured = Image.open(path).convert("RGB")
        samples = []
        if captured.size == reference.size:
            for row in range(1, 6):
                for column in range(1, 6):
                    x, y = width * column // 6, height * row // 6
                    box = (max(0, x-2), max(0, y-2), min(width, x+3), min(height, y+3))
                    before = ImageStat.Stat(reference.crop(box)).mean
                    after = ImageStat.Stat(captured.crop(box)).mean
                    samples.append(dict(x=x, y=y, inputRGB=before, photoRGB=after,
                                        maxChannelDelta=max(abs(a-b) for a, b in zip(before, after))))
        save_json(out / (name + "-pixels.json"), dict(inputSize=list(reference.size), photoSize=list(captured.size),
                  tolerance=15, method="25 fixed grid samples; 5x5 pixel mean per sample", samples=samples))
        check(name + " dimensions and real screenshot pixels", captured.size == reference.size and len(samples) == 25 and
              all(sample["maxChannelDelta"] <= 15 for sample in samples), name + "-pixels.json")

    try:
        run.start(dict(SIMRUN_LOCATION_FILE=str(out / "location.json"), SIMRUN_CAMERA_FILE=str(out / "camera.json")))
        run.wait_ready()
        initial = state("01-initial")
        check("location starts undetermined", initial["authorization"] == 0, "01-initial.json")
        run.tap("Request location")
        fix = wait_state("02-single-fix", lambda s: s["updates"] == 1)
        check("single coordinate and authorization", fix["authorization"] == 4 and fix["latitude"] == 31.22046 and
              fix["longitude"] == 121.45801 and fix["accuracy"] == 5, "02-single-fix.json")
        time.sleep(1.3)
        check("one-shot does not repeat", state("03-single-stable")["updates"] == fix["updates"], "03-single-stable.json")
        run.tap("Start location")
        wait_state("04-continuous", lambda s: s["updates"] >= 3)
        location(latitude=31.2304, longitude=121.4737)
        changed = wait_state("05-coordinate-changed", lambda s: s.get("latitude") == 31.2304 and s.get("longitude") == 121.4737)
        check("continuous fixes use new coordinate and timestamp", changed["timestamp"] > fix["timestamp"], "05-coordinate-changed.json")
        run.tap("Stop location")
        stopped = state("06-location-stopped")
        time.sleep(1.3)
        check("stop location cancels callbacks", state("07-location-stable")["updates"] == stopped["updates"], "06-location-stopped.json + 07-location-stable.json")
        location(authorization="denied")
        run.tap("Request location")
        denied = wait_state("08-location-denied", lambda s: s["authorization"] == 2 and s.get("error") == "kCLErrorDomain:1")
        check("denied location emits no fix or cached coordinate", denied["updates"] == stopped["updates"] and not denied["cachedLocationAvailable"], "08-location-denied.json")
        location(authorization="authorizedWhenInUse")
        run.tap("Request location")
        restored = wait_state("09-location-restored", lambda s: s["updates"] == stopped["updates"] + 1)
        check("location restores", restored["authorization"] == 4, "09-location-restored.json")

        run.tap("Start camera")
        frames = wait_state("10-camera-frames", lambda s: s["frames"] >= 3 and s.get("cameraRunning") is True)
        check("camera receives screenshot dimensions", frames["frameWidth"] == width and frames["frameHeight"] == height and
              frames["videoDevices"] == 2 and frames["cameraAllowed"], "10-camera-frames.json")
        check("video-range NV12, color and propagated EXIF", frames["framePixelFormat"] == int.from_bytes(b"420v", "big") and
              len(frames.get("frameFirstRGB", [])) == 3 and all(abs(a-b) <= 15 for a, b in zip(frames["frameFirstRGB"], first_rgb)) and
              frames["frameExifPresent"] and frames["ptsMonotonic"], "10-camera-frames.json")
        check("virtual exposure reset completes", frames.get("exposureResetCompleted") is True, "10-camera-frames.json")
        run.screenshot("10-preview.png")
        for index in (1, 2):
            before = run.state()
            run.tap("Take photo")
            name = "11-photo-" + str(index)
            after = wait_state(name, lambda s: s["completions"] >= before["completions"] + 1)
            time.sleep(.4)
            after = state(name)
            check(name + " has one processing and completion", after["photos"] == before["photos"] + 1 and
                  after["processingCallbacks"] == before["processingCallbacks"] + 1 and
                  after["completions"] == before["completions"] + 1 and after["photoErrors"] == before["photoErrors"], name + ".json")
            target = out / (name + ".jpg")
            shutil.copy2(after["photoPath"], target)
            compare_photo(target, name)
        run.screenshot("12-photo.png")
        run.tap("Stop camera")
        stopped = state("13-camera-stopped")
        time.sleep(1.3)
        stable = state("14-camera-stable")
        check("stop camera ends frame delivery", not stable["cameraRunning"] and stable["frames"] == stopped["frames"], "13-camera-stopped.json + 14-camera-stable.json")
        for button, code, name in [("Use NV12 full range", b"420f", "15-full-range"), ("Use BGRA", b"BGRA", "16-bgra")]:
            before = run.state()
            run.tap(button)
            value = wait_state(name, lambda s: s["frames"] > before["frames"] and s.get("framePixelFormat") == int.from_bytes(code, "big"))
            check(button + " frame format and metadata", value["frameWidth"] == width and value["frameHeight"] == height and
                  len(value.get("frameFirstRGB", [])) == 3 and all(abs(a-b) <= 15 for a, b in zip(value["frameFirstRGB"], first_rgb)) and
                  value["frameExifPresent"] and value["ptsMonotonic"], name + ".json")
        configure_permission("denied")
        revoked = wait_state("17-camera-revoked", lambda s: not s["cameraRunning"] and s["cameraAuthorization"] == 2)
        time.sleep(1.3)
        stable = state("18-revoked-stable")
        check("revoked camera stops frame delivery", stable["frames"] == revoked["frames"], "17-camera-revoked.json + 18-revoked-stable.json")
        run.tap("Take photo")
        failure = wait_state("19-revoked-photo", lambda s: s["completions"] >= stable["completions"] + 1)
        time.sleep(.4)
        failure = state("19-revoked-photo")
        check("revoked photo fails once without cached image", failure["photos"] == stable["photos"] and
              failure["photoErrors"] == stable["photoErrors"] + 1 and failure["processingCallbacks"] == stable["processingCallbacks"] + 1 and
              failure["completions"] == stable["completions"] + 1 and failure.get("lastPhotoErrorHadImage") is False and
              bool(failure.get("lastPhotoErrorDomain")), "19-revoked-photo.json")
        run.screenshot("19-revoked-preview.png")
        configure_permission("authorized")
        run.tap("Start camera")
        resumed = wait_state("20-camera-restored", lambda s: s["cameraRunning"] and s["frames"] >= failure["frames"] + 3)
        check("camera resumes after explicit restore and reopen", resumed["cameraAuthorization"] == 3 and resumed["ptsMonotonic"], "20-camera-restored.json")
        run.tap("Stop camera")
        report["completed"] = True
        save()
        print("All checks passed:", out / "acceptance.json", flush=True)
    except BaseException as error:
        report["failure"] = str(error)
        save()
        raise
    finally:
        run.close()


if __name__ == "__main__":
    main()
