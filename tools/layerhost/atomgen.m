// atomgen.m — run at build time on the Mac: prints macOS QuartzCore's static atom names as a C header (atoms_mac.h) for
// the layerhost translator (src/sim/layerhost/xlate.c).
#import <Foundation/Foundation.h>

extern CFStringRef CAAtomGetString(unsigned);

int main(void) {
  @autoreleasepool {
    printf("// Generated by atomgen from macOS QuartzCore %s.\n",
           [[NSBundle bundleWithIdentifier:@"com.apple.QuartzCore"].infoDictionary[@"CFBundleVersion"] UTF8String] ?: "?");
    printf("static const char *const kMacAtomNames[] = {\n  NULL,\n");
    for (unsigned a = 1; a < 4096; a++) {
      NSString *s = (__bridge NSString *)CAAtomGetString(a);
      if (!s || [s isEqualToString:@"<unknown>"]) break;
      printf("  \"%s\",\n", s.UTF8String);
    }
    printf("};\n");
  }
}
